/// The window's whole key map. Key codes are the Carbon `kVK_` values,
/// written out so this file needs no Carbon.
///   Return, keypad Enter            paste
///   Command-Return / Enter          copy only
///   Escape                          close
///   Down, Control-N / Up, Control-P move
///   Option-P                        pin or unpin
///   Command-Delete / Forward Delete remove
/// Anything else goes to the search field, Option-Delete (delete a word)
/// included.
enum ClipboardHistoryKeyAction: Equatable {
    case choose(ClipboardHistoryChoice)
    case move(Int)
    case togglePin
    case remove
    case close
    case showActions
    case showTypeMenu

    private static let returnKey: UInt16 = 36
    private static let keypadEnter: UInt16 = 76
    private static let escape: UInt16 = 53
    private static let downArrow: UInt16 = 125
    private static let upArrow: UInt16 = 126
    private static let pKey: UInt16 = 35
    private static let kKey: UInt16 = 40
    private static let delete: UInt16 = 51
    private static let forwardDelete: UInt16 = 117

    static func action(keyCode: UInt16, modifiers: ClipboardHistoryModifiers,
                       key: String?) -> ClipboardHistoryKeyAction? {
        switch keyCode {
        case escape:
            return .close
        case returnKey, keypadEnter:
            if modifiers.isEmpty { return .choose(.paste) }
            if modifiers == [.command] { return .choose(.copyOnly) }
            return nil
        case downArrow:
            return .move(1)
        case upArrow:
            return .move(-1)
        case pKey where modifiers == [.option]:
            return .togglePin
        case pKey where modifiers == [.command]:
            return .showTypeMenu
        case kKey where modifiers == [.command]:
            return .showActions
        case delete where modifiers == [.command], forwardDelete where modifiers == [.command]:
            return .remove
        default:
            break
        }
        if modifiers == [.control] {
            if key == "n" { return .move(1) }
            if key == "p" { return .move(-1) }
        }
        return nil
    }
}

// MARK: - Placement

/// Centred on the visible frame of the display under the pointer, shrunk
/// to fit inside a margin.
enum ClipboardHistoryPlacement {
    static let contentSize = CGSize(width: 760, height: 480)
    static let listWidth: CGFloat = 290
    static let margin: CGFloat = 16

    static func frame(size: CGSize = contentSize, pointer: CGPoint,
                      screens: [(frame: CGRect, visible: CGRect)]) -> CGRect {
        // NSMouseInRect for an unflipped screen: the top edge belongs to the
        // screen, the bottom edge to the one below.
        let screen = screens.first { screen in
            pointer.x >= screen.frame.minX && pointer.x < screen.frame.maxX
                && pointer.y > screen.frame.minY && pointer.y <= screen.frame.maxY
        } ?? screens.first
        guard let visible = screen?.visible else { return CGRect(origin: .zero, size: size) }
        let room = visible.insetBy(dx: margin, dy: margin)
        let width = max(0, min(size.width, room.width))
        let height = max(0, min(size.height, room.height))
        return CGRect(x: (visible.midX - width / 2).rounded(),
                      y: (visible.midY - height / 2).rounded(),
                      width: width, height: height)
    }
}

// MARK: - Paste gate

/// When Command-V may be posted after the window ordered out. One posted
/// while a FixDock window is key lands in FixDock, and one posted while
/// another app is in front pastes in the wrong place.
enum ClipboardHistoryPasteGate {
    enum Decision: Equatable {
        case post
        case wait
        /// Leave it copied and say so.
        case giveUp
    }

    static let pollInterval: TimeInterval = 0.02
    static let maxAttempts = 25

    static func decide(frontmostPID: pid_t?, targetPID: pid_t, targetTerminated: Bool,
                       ownWindowIsKey: Bool, attempt: Int) -> Decision {
        if targetTerminated { return .giveUp }
        if frontmostPID == targetPID, !ownWindowIsKey { return .post }
        return attempt >= maxAttempts ? .giveUp : .wait
    }
}

/// Bundle ids trimmed, empty ones and repeats dropped, order kept.
enum ClipboardHistoryBundleList {
    static func sanitized(_ bundleIDs: [String]) -> [String] {
        var seen = Set<String>()
        return bundleIDs
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { !$0.isEmpty && seen.insert($0).inserted }
    }
}
