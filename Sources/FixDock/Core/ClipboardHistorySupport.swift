struct ClipboardHistoryOrigin: Equatable {
    var sourceMark: String?
    var remote: Bool
}

enum ClipboardHistoryRead: Equatable {
    case unchanged(changeCount: Int)
    case skipped(changeCount: Int, ClipboardHistoryCapturePolicy.Skip, origin: ClipboardHistoryOrigin? = nil)
    case text(changeCount: Int, plain: String?, webURL: String?, origin: ClipboardHistoryOrigin)
    case files(changeCount: Int, [ClipboardFileRef], origin: ClipboardHistoryOrigin)
    case image(changeCount: Int, Data, origin: ClipboardHistoryOrigin)

    var changeCount: Int {
        switch self {
        case .unchanged(let changeCount), .skipped(let changeCount, _, _), .text(let changeCount, _, _, _),
             .files(let changeCount, _, _), .image(let changeCount, _, _):
            return changeCount
        }
    }

    var origin: ClipboardHistoryOrigin? {
        switch self {
        case .unchanged: return nil
        case .skipped(_, _, let origin): return origin
        case .text(_, _, _, let origin), .files(_, _, let origin), .image(_, _, let origin): return origin
        }
    }
}

enum ClipboardHistoryCapturePolicy {
    enum Skip: Equatable {
        /// The app said the content is a secret.
        case secret
        /// Content its app is about to take back, or made up rather than
        /// copied (a dictation app typing through the clipboard).
        case transient
        case notRecorded
        case ownWrite
        case tooLarge
    }

    enum Plan: Equatable {
        case skip(Skip)
        case files
        case text
        case image(type: String)
    }

    /// The nspasteboard.org marks plus the system's own. Honouring an app's
    /// word is the only way to leave a password out that does not depend on
    /// guessing what the text looks like.
    static let secretTypes: Set<String> = ["org.nspasteboard.ConcealedType", "com.apple.is-sensitive"]
    static let transientTypes: Set<String> = ["org.nspasteboard.TransientType",
                                              "org.nspasteboard.AutoGeneratedType"]
    static let fileURLTypes: Set<String> = ["public.file-url", "NSFilenamesPboardType"]
    static let plainTextTypes: Set<String> = ["public.utf8-plain-text", "public.utf16-plain-text",
                                              "public.utf16-external-plain-text", "NSStringPboardType"]
    static let webURLTypes: Set<String> = ["public.url", "NSURLPboardType"]
    static let rasterTypes: [String] = [
        "com.compuserve.gif", "public.png", "Apple PNG pasteboard type", "public.jpeg", "public.heic",
        "public.tiff", "NeXT TIFF v4.0 pasteboard type",
    ]
    static let maxFilesPerCopy = 32
    static let temporaryFolders = ["/tmp", "/private/tmp", "/var/folders", "/private/var/folders"]

    static func plan(forTypes types: [String], recordsMedia: Bool, realFiles: Bool = true) -> Plan {
        let present = Set(types)
        if !present.isDisjoint(with: secretTypes) { return .skip(.secret) }
        if !present.isDisjoint(with: transientTypes) { return .skip(.transient) }
        if realFiles, !present.isDisjoint(with: fileURLTypes) { return recordsMedia ? .files : .skip(.notRecorded) }
        if !present.isDisjoint(with: plainTextTypes) { return .text }
        if let raster = rasterTypes.first(where: present.contains) {
            return recordsMedia ? .image(type: raster) : .skip(.notRecorded)
        }
        if !present.isDisjoint(with: webURLTypes) { return .text }
        return .skip(.notRecorded)
    }

    static func fileRefs(_ files: [(path: String, isDirectory: Bool)], home: String) -> [ClipboardFileRef] {
        let skipped = temporaryFolders + [(home as NSString).appendingPathComponent("Library/Caches")]
        var seen = Set<String>()
        var refs: [ClipboardFileRef] = []
        for file in files where refs.count < maxFilesPerCopy {
            guard !skipped.contains(where: { file.path == $0 || file.path.hasPrefix($0 + "/") }),
                  let ref = ClipboardFileRef(path: file.path, isDirectory: file.isDirectory),
                  seen.insert(ref.path).inserted else { continue }
            refs.append(ref)
        }
        return refs
    }

    /// The text an entry keeps, or nil. Each candidate goes through
    /// `cleanLink` (the URL cleaner's rule, nil to keep it as copied) before
    /// one is picked, so a dirty copy and the cleaner's later rewrite of it
    /// come out as the same string and refresh one entry.
    static func recordedText(plain: String?, webURL: String?,
                             cleanLink: (String) -> String?) -> String? {
        let plain = plain.map { cleanLink($0) ?? $0 }
        let webURL = webURL.map { cleanLink($0) ?? $0 }
        return ClipboardHistoryPasteboardText.preferredText(webURLString: webURL, plainText: plain)
            .flatMap(ClipboardHistoryStore.storableText)
    }

    /// FixDock's own write, by the source mark every FixDock writer sets.
    /// An empty mark, or one longer than any bundle id, is no mark.
    static func isOwnWrite(sourceMark: String?, ownBundleID: String?) -> Bool {
        guard let ownBundleID,
              let mark = sourceMark?.trimmingCharacters(in: .whitespacesAndNewlines),
              !mark.isEmpty, mark.utf8.count <= 255 else { return false }
        return mark == ownBundleID
    }
}

/// Decides whether a polled change count is a new copy.
///
/// The count lives in the pasteboard server: when it restarts, the new one
/// counts again from near zero, and a plain `read > last` would reject every
/// copy until it climbed past the old count. `since` is the count known when
/// the read was queued, so only a restart makes `read` lower than it. `last`
/// is the count known now, which a FixDock write settling while the read was
/// in flight may have raised past `read`; that read stays rejected.
enum ClipboardHistoryChangeCount {
    static func accepted(read: Int, since: Int, last: Int) -> Int? {
        if read < since { return read }
        return read > last ? read : nil
    }
}

/// Main-thread capture admission. Expiring a result does not release the
/// read still queued on the lane; stop and start must not release it either.
struct ClipboardHistoryCaptureState {
    private(set) var generation = 0
    private(set) var inFlight = false
    private(set) var needsBaseline = true

    mutating func restart() {
        generation &+= 1
        needsBaseline = true
    }

    mutating func invalidate() {
        generation &+= 1
    }

    mutating func begin() -> Int? {
        guard !inFlight else { return nil }
        inFlight = true
        generation &+= 1
        return generation
    }

    func accepts(_ token: Int) -> Bool {
        token == generation
    }

    mutating func expire(_ token: Int) {
        if accepts(token) { invalidate() }
    }

    mutating func finish() {
        inFlight = false
    }

    mutating func didBaseline() {
        needsBaseline = false
    }
}

/// Upstream's choice between the plain text and the web URL, except that
/// the address is normalized only to compare the two: the chosen candidate
/// keeps its own spelling. `URL(string:)` percent-encodes non-ASCII on
/// macOS 14 and later, which would store a Hangul link as `%ED%95%9C…` and
/// differ from what the URL cleaner writes back.
enum ClipboardHistoryPasteboardText {
    static func preferredText(webURLString: String?, plainText: String?) -> String? {
        let plain = trimmed(plainText)
        if let plain, normalizedWebURL(plain) != nil { return plain }
        guard let webURL = trimmed(webURLString), let normalizedWeb = normalizedWebURL(webURL) else {
            return plain
        }
        guard let plain else { return webURL }
        return shouldPreferWebURL(normalizedWeb, over: plain) ? webURL : plain
    }

    private static func shouldPreferWebURL(_ webURL: String, over plain: String) -> Bool {
        guard !plain.contains(where: \.isWhitespace) else { return false }
        if plain.hasPrefix("//") { return true }
        let stripped = stripWebScheme(webURL)
        return plain == stripped.withSlashes || plain == stripped.withoutSlashes
    }

    private static func normalizedWebURL(_ text: String) -> String? {
        // A copy of several links keeps them apart with whitespace, which
        // `URL` would escape and take as one link.
        guard !text.contains(where: \.isWhitespace),
              let url = URL(string: text),
              let scheme = url.scheme?.lowercased(),
              scheme == "http" || scheme == "https",
              url.host != nil else { return nil }
        return url.absoluteString
    }

    private static func stripWebScheme(_ value: String) -> (withSlashes: String, withoutSlashes: String) {
        let lower = value.lowercased()
        let withSlashes: String
        if lower.hasPrefix("http://") {
            withSlashes = "//" + String(value.dropFirst("http://".count))
        } else if lower.hasPrefix("https://") {
            withSlashes = "//" + String(value.dropFirst("https://".count))
        } else {
            withSlashes = value
        }
        return (withSlashes, String(withSlashes.drop { $0 == "/" }))
    }

    private static func trimmed(_ raw: String?) -> String? {
        guard let raw else { return nil }
        let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        return text.isEmpty ? nil : text
    }
}

struct ClipboardHistorySearchCandidate: Equatable {
    var index: Int
    var isPinned: Bool
    var normalizedText: String
    var words: Set<String>
}

struct ClipboardHistoryIndex {
    private var kinds: [UUID: ClipboardHistoryKind] = [:]
    private var folded: [UUID: (normalized: String, words: Set<String>)] = [:]
    private var stamp: Int?

    mutating func results(_ entries: [ClipboardHistoryEntry], query: String,
                          filter: ClipboardHistoryFilter, stamp: Int) -> [Int] {
        prune(entries, stamp: stamp)
        let admitted = entries.indices.filter { filter.admits(kind(of: entries[$0])) }
        guard !ClipboardHistorySearch.searchTokens(for: ClipboardHistorySearch.normalized(query)).isEmpty
        else { return admitted }
        let candidates = admitted.compactMap { index -> ClipboardHistorySearchCandidate? in
            let entry = entries[index]
            guard let value = foldedText(of: entry) else { return nil }
            return ClipboardHistorySearchCandidate(index: index, isPinned: entry.isPinned,
                                                   normalizedText: value.normalized, words: value.words)
        }
        return ClipboardHistorySearch.rankedIndexes(candidates: candidates, matching: query)
    }

    mutating func kind(of entry: ClipboardHistoryEntry) -> ClipboardHistoryKind {
        if let kind = kinds[entry.id] { return kind }
        let kind = ClipboardHistoryClassifier.kind(of: entry.content)
        kinds[entry.id] = kind
        return kind
    }

    mutating func clear() {
        kinds.removeAll()
        folded.removeAll()
        stamp = nil
    }

    private mutating func foldedText(of entry: ClipboardHistoryEntry) -> (normalized: String, words: Set<String>)? {
        if let value = folded[entry.id] { return value }
        guard let text = entry.content.searchText else { return nil }
        let normalized = ClipboardHistorySearch.normalized(text)
        let value = (normalized, ClipboardHistorySearch.words(in: normalized))
        folded[entry.id] = value
        return value
    }

    private mutating func prune(_ entries: [ClipboardHistoryEntry], stamp: Int) {
        guard self.stamp != stamp else { return }
        self.stamp = stamp
        let ids = Set(entries.map(\.id))
        kinds = kinds.filter { ids.contains($0.key) }
        folded = folded.filter { ids.contains($0.key) }
    }
}

extension ClipboardHistoryContent {
    var searchText: String? {
        switch self {
        case .text(let text): return text
        case .file(let file): return file.name + " " + file.path
        case .image: return nil
        }
    }
}

enum ClipboardHistorySearch {
    /// Every token must match; the exact text, a prefix, whole words and pins
    /// rank first, and ties keep the history's order.
    static func rankedIndexes(candidates: [ClipboardHistorySearchCandidate], matching query: String) -> [Int] {
        let normalizedQuery = normalized(query)
        let tokens = searchTokens(for: normalizedQuery)
        guard !tokens.isEmpty else { return candidates.map(\.index) }
        return candidates
            .compactMap { candidate -> (index: Int, score: Int)? in
                let text = candidate.normalizedText
                guard tokens.allSatisfy({ text.contains($0) }) else { return nil }
                return (candidate.index, score(for: text, words: candidate.words,
                                               normalizedQuery: normalizedQuery, tokens: tokens,
                                               isPinned: candidate.isPinned))
            }
            .sorted { $0.score != $1.score ? $0.score > $1.score : $0.index < $1.index }
            .map(\.index)
    }

    static func searchTokens(for query: String) -> [String] {
        query.split(whereSeparator: \.isWhitespace).map(String.init).filter { !$0.isEmpty }
    }

    /// Matching ranges in `text`, ignoring case, diacritics and width.
    static func highlightRanges(in text: String, tokens: [String]) -> [Range<String.Index>] {
        guard !text.isEmpty, !tokens.isEmpty else { return [] }
        var ranges: [Range<String.Index>] = []
        for token in tokens where !token.isEmpty {
            var search = text.startIndex..<text.endIndex
            while search.lowerBound < text.endIndex,
                  let range = text.range(of: token,
                                         options: [.caseInsensitive, .diacriticInsensitive, .widthInsensitive],
                                         range: search) {
                ranges.append(range)
                if range.upperBound == search.lowerBound { break }
                search = range.upperBound..<text.endIndex
            }
        }
        return ranges
    }

    static func words(in normalizedText: String) -> Set<String> {
        Set(normalizedText.split(whereSeparator: \.isWhitespace).map(String.init))
    }

    static func normalized(_ value: String) -> String {
        value
            // No locale: Turkish would fold a dotted I to a dotless one, and
            // "istanbul" would stop finding "ISTANBUL".
            .folding(options: [.caseInsensitive, .diacriticInsensitive, .widthInsensitive], locale: nil)
            .lowercased()
            .replacingOccurrences(of: "\n", with: " ")
            .replacingOccurrences(of: "\t", with: " ")
            .trimmingCharacters(in: .whitespacesAndNewlines)
    }

    private static func score(for text: String, words: Set<String>, normalizedQuery: String,
                              tokens: [String], isPinned: Bool) -> Int {
        var score = isPinned ? 30 : 0
        if text == normalizedQuery { score += 1_200 }
        if text.hasPrefix(normalizedQuery) { score += 900 }
        if text.contains(normalizedQuery) { score += 700 }
        for token in tokens {
            if words.contains(token) {
                score += 140
            } else if words.contains(where: { $0.hasPrefix(token) }) {
                score += 80
            } else {
                score += 40
            }
        }
        return score
    }
}

enum ClipboardHistoryFocus {
    /// A composing input method always owns Return, the arrows and Escape:
    /// claiming them leaves the search field unusable in Korean, Japanese and
    /// Chinese. Outside composition the search field (a field editor) leaves
    /// them to the list.
    static func textViewOwnsKeys(isComposing: Bool, isFieldEditor: Bool, isEditable: Bool) -> Bool {
        isComposing || (isEditable && !isFieldEditor)
    }
}

