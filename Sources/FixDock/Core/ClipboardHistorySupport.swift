struct ClipboardHistoryModifiers: OptionSet, Hashable {
    let rawValue: Int
    static let control = ClipboardHistoryModifiers(rawValue: 1 << 0)
    static let option = ClipboardHistoryModifiers(rawValue: 1 << 1)
    static let shift = ClipboardHistoryModifiers(rawValue: 1 << 2)
    static let command = ClipboardHistoryModifiers(rawValue: 1 << 3)
}

enum ClipboardHistoryChoice: Equatable {
    /// Close, write, and paste into the app that was in front.
    case paste
    /// Close and write only.
    case copyOnly
}

struct ClipboardHistoryItem: Identifiable, Equatable {
    let entry: ClipboardHistoryEntry
    let kind: ClipboardHistoryKind
    var id: UUID { entry.id }
}

enum ClipboardHistoryAction: Hashable, CaseIterable {
    case paste, copyOnly, swapLayout, togglePin, showInFinder, delete

    /// Longest text `swapLayout` is offered for; menus ask on every render.
    static let swapLayoutLimit = 2_000

    func applies(to content: ClipboardHistoryContent) -> Bool {
        if self == .showInFinder, case .text = content { return false }
        if self == .swapLayout {
            // Only text the other layout would type differently.
            guard case .text(let text) = content, text.utf16.count <= Self.swapLayoutLimit else { return false }
            return HangulTwoSet.swappedLayout(text) != text
        }
        return true
    }
}

